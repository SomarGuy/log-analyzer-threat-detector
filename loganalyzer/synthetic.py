def generate(out_dir: str | Path, seed: int = 1337) -> Dict[str, Path]:
    """Write the synthetic dataset and ground-truth file into ``out_dir``; return the file paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    notice = NOTICE.format(seed=seed)
    truth: List[dict] = []
    # independent RNGs per file keep each file stable even if another generator changes
    auth = gen_auth(random.Random(seed), truth)
    dc, ws = gen_windows(random.Random(seed + 1), truth)
    web = gen_web(random.Random(seed + 2), truth)
    paths = {
        "auth": out / "auth.log", "windows_csv": out / "windows_security_dc01.csv",
        "windows_json": out / "windows_security_ws12.json", "web": out / "access.log",
        "truth": out / "ground_truth.json",
    }
    auth[0] = "# " + notice
    web[0] = "# " + notice
    paths["auth"].write_text("\n".join(auth) + "\n", encoding="utf-8")
    paths["web"].write_text("\n".join(web) + "\n", encoding="utf-8")
    with paths["windows_csv"].open("w", encoding="utf-8", newline="") as fh:
        fh.write("# " + notice + "\n")
        writer = csv.DictWriter(fh, fieldnames=WIN_FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(dc)
    paths["windows_json"].write_text(json.dumps({"_synthetic_notice": notice, "events": [{k: v for k, v in r.items() if v != ""} for r in ws]}, indent=1) + "\n", encoding="utf-8")
    paths["truth"].write_text(json.dumps({"_synthetic_notice": notice, "seed": seed, "scenarios": truth}, indent=2) + "\n", encoding="utf-8")
    return paths
