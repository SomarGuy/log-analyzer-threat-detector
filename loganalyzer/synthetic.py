def _auth_line(ts: datetime, proc: str, pid: int, msg: str, host: str = WEB_HOST) -> Tuple[datetime, str]:
    stamp = "{} {:>2} {}".format(ts.strftime("%b"), ts.day, ts.strftime("%H:%M:%S"))
    return ts, "{} {} {}[{}]: {}".format(stamp, host, proc, pid, msg)


