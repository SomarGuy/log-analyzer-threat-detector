class _Clock:
    """Tiny helper so scenario code reads top to bottom."""

    def __init__(self, rng: random.Random):
        self.rng = rng

    def at(self, day: int, hh: int, mm: int, ss: int = 0) -> datetime:
        return WEEK_START + timedelta(days=day, hours=hh, minutes=mm, seconds=ss)


def _b64_ps(text: str) -> str:
    return base64.b64encode(text.encode("utf-16-le")).decode()


