"""JSON and Markdown report writers."""
from __future__ import annotations

import json
from collections import Counter
from datetime import datetime
from typing import Any, Dict, List, Optional

from . import __version__
from .engine import AnalysisResult, mitre_summary, top_attackers
from .models import SEVERITY_ORDER

SCHEMA_VERSION = 1
SEV_LABEL = {"critical": "CRITICAL", "high": "HIGH", "medium": "MEDIUM", "low": "LOW"}


def build_report(result: AnalysisResult, synthetic: bool = False, generated_at: Optional[datetime] = None,
                 title: str = "Log Analyzer incident report") -> Dict[str, Any]:
    """Assemble the JSON document that the dashboard and the Markdown writer both consume."""
    generated_at = generated_at or datetime.now().replace(microsecond=0)
    sev_counts = Counter(a.severity for a in result.alerts)
    return {
        "schema_version": SCHEMA_VERSION,
        "meta": {
            "title": title, "tool": "loganalyzer", "version": __version__,
            "generated_at": generated_at.strftime("%Y-%m-%dT%H:%M:%S"),
            "synthetic": synthetic,
            "synthetic_notice": ("SYNTHETIC DATA: every log line in this report was generated by a script "
                                 "(loganalyzer/synthetic.py). No real systems, users or attackers are shown; IPs come "
                                 "from reserved documentation ranges.") if synthetic else "",
            "inputs": [s.as_dict() for s in result.parse_stats],
        },
        "summary": {
            "alerts_total": len(result.alerts),
            "incidents_total": len(result.incidents),
            "severity_counts": {s: sev_counts.get(s, 0) for s in ("critical", "high", "medium", "low")},
            "events_total": result.events_total,
            "events_by_source": result.stats.get("events_by_source", {}),
            "time_range": result.stats.get("time_range", []),
            "unique_source_ips": result.stats.get("unique_source_ips", 0),
            "top_attackers": top_attackers(result.alerts),
            "mitre": mitre_summary(result.alerts),
            "volume_by_hour": result.stats.get("volume_by_hour", []),
        },
        "incidents": [i.as_dict() for i in result.incidents],
        "alerts": [a.as_dict() for a in result.alerts],
        "rules": [{"id": r.id, "name": r.name, "type": r.type, "severity": r.severity, "sources": r.sources,
                   "enabled": r.enabled, "mitre": [m["id"] for m in r.mitre],
                   "params": {k: v for k, v in r.params.items() if k != "patterns"}} for r in result.rules],
    }


def write_json(report: Dict[str, Any], path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(report, fh, indent=2, sort_keys=False)
        fh.write("\n")


def _md_escape(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(report: Dict[str, Any]) -> str:
    meta, summ = report["meta"], report["summary"]
    out: List[str] = []
    out.append("# {}".format(meta["title"]))
    out.append("")
    if meta["synthetic"]:
        out.append("> **{}**".format(meta["synthetic_notice"]))
        out.append("")
    out.append("Generated {} by `{}` v{}.".format(meta["generated_at"], meta["tool"], meta["version"]))
    out.append("")
    out.append("## Executive summary")
    out.append("")
    sc = summ["severity_counts"]
    rng = " to ".join(summ["time_range"]) if summ["time_range"] else "n/a"
    out.append("- **Period analysed:** {}".format(rng))
    out.append("- **Events analysed:** {:,} ({})".format(
        summ["events_total"], ", ".join("{} {:,}".format(k, v) for k, v in sorted(summ["events_by_source"].items()))))
    out.append("- **Alerts:** {} (critical {}, high {}, medium {}, low {})".format(
        summ["alerts_total"], sc["critical"], sc["high"], sc["medium"], sc["low"]))
    out.append("- **Correlated incidents:** {}".format(summ["incidents_total"]))
    out.append("- **Unique source IPs seen in logs:** {}".format(summ["unique_source_ips"]))
    out.append("")
    if report["incidents"]:
        out.append("## Incidents")
        out.append("")
        for inc in report["incidents"]:
            out.append("### {} [{}] {}".format(inc["id"], SEV_LABEL[inc["severity"]], inc["title"]))
            out.append("")
            out.append("- **Window:** {} to {}".format(inc["first_seen"], inc["last_seen"]))
            out.append("- **Source IPs:** {}".format(", ".join(inc["source_ips"]) or "none recorded"))
            out.append("- **Hosts:** {}".format(", ".join(inc["hosts"]) or "n/a"))
            out.append("- **Alerts:** {}".format(", ".join(inc["alert_ids"])))
            out.append("- **Sequence:**")
            for line in inc["narrative"]:
                out.append("  1. {}".format(line))
            out.append("")
    out.append("## Top source IPs (by severity, then alert count)")
    out.append("")
    if summ["top_attackers"]:
        out.append("| IP | Scope | Max severity | Alerts | Events | Rules |")
        out.append("|---|---|---|---|---|---|")
        for row in summ["top_attackers"]:
            out.append("| `{}` | {} | {} | {} | {} | {} |".format(
                row["ip"], "internal" if row.get("internal") else "external", row["max_severity"], row["alerts"],
                row["events"], ", ".join(row["rules"])))
    else:
        out.append("No alerts with a source IP.")
    out.append("")
    out.append("## MITRE ATT&CK coverage of this report")
    out.append("")
    if summ["mitre"]:
        out.append("| Tactic | Technique | Name | Alerts |")
        out.append("|---|---|---|---|")
        for m in summ["mitre"]:
            out.append("| {} | [{}](https://attack.mitre.org/techniques/{}/) | {} | {} |".format(
                m["tactic"], m["id"], m["id"].replace(".", "/"), _md_escape(m["name"]), m["alerts"]))
    else:
        out.append("No techniques observed.")
    out.append("")
    out.append("## Alerts")
    out.append("")
    for a in sorted(report["alerts"], key=lambda x: (-SEVERITY_ORDER[x["severity"]], x["first_seen"])):
        out.append("### {} [{}] {}".format(a["id"], SEV_LABEL[a["severity"]], a["title"]))
        out.append("")
        out.append("- **Rule:** {}  |  **Incident:** {}".format(a["rule_id"], a["incident_id"] or "none"))
        out.append("- **When:** {} to {} ({} event{})".format(a["first_seen"], a["last_seen"], a["count"],
                                                              "" if a["count"] == 1 else "s"))
        out.append("- **Source IPs:** {}  |  **Accounts:** {}  |  **Hosts:** {}".format(
            ", ".join(a["source_ips"]) or "n/a", ", ".join(a["users"][:8]) or "n/a", ", ".join(a["hosts"]) or "n/a"))
        out.append("- **MITRE ATT&CK:** {}".format(", ".join("{} {}".format(m["id"], m["name"]) for m in a["mitre"])))
        out.append("- **Why it fired:** {}".format(a["description"]))
        if a["details"]:
            out.append("- **Details:** {}".format("; ".join("{}={}".format(k, v) for k, v in a["details"].items())))
        out.append("")
        out.append("Timeline:")
        out.append("")
        for t in a["timeline"][:8]:
            out.append("- `{}` {}".format(t["ts"], _md_escape(t["event"])))
        out.append("")
        out.append("Recommended response:")
        out.append("")
        for i, step in enumerate(a["recommended_response"], 1):
            out.append("{}. {}".format(i, step))
        out.append("")
        out.append("<details><summary>Evidence (raw log lines)</summary>")
        out.append("")
        out.append("```text")
        out.extend(line.replace("```", "'''") for line in a["evidence"])
        out.append("```")
        out.append("</details>")
        out.append("")
    out.append("## Input files and parse quality")
    out.append("")
    out.append("| File | Source | Lines | Parsed | Ignored | Malformed |")
    out.append("|---|---|---|---|---|---|")
    for s in meta["inputs"]:
        out.append("| `{}` | {} | {} | {} | {} | {} |".format(s["path"], s["source"], s["lines"], s["parsed"], s["ignored"], s["malformed"]))
    out.append("")
    out.append("*Timestamps are used as written in each log (no timezone normalisation). Detection is "
               "rule-based and will miss anything the rules do not describe; treat alerts as leads to investigate, not verdicts.*")
    out.append("")
    return "\n".join(out)
